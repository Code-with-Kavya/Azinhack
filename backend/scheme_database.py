def seed_schemes() -> None:
    """Seed government schemes into SQLite database if the table is empty or missing entries.

    Guarantees idempotency: checks existing scheme names to avoid duplicate inserts.
    """
    with Session(engine) as session:
        existing_names = set(session.exec(select(Scheme.name)).all())
        to_add = [Scheme(**item) for item in SCHEMES if item["name"] not in existing_names]

        if to_add:
            session.add_all(to_add)
            session.commit()
            logger.info(f"Seeded {len(to_add)} schemes (total in DB: {len(existing_names) + len(to_add)}).")
        else:
            logger.info(f"Schemes already seeded ({len(existing_names)} schemes in database).")
